def initialize(context):
    # 这是聚宽平台规定好的"初始化函数"
    #
    # 平台在启动策略时，会先调用它一次
    #
    # 你可以把它理解成：
    # "这份策略刚开始运行时，先做哪些准备工作"
    #
    # 这里的 `context` 不是你自己创建的变量，
    # 而是聚宽平台传进来的"策略运行上下文对象"
    #
    # 这个对象里通常会有：
    # - 账户信息
    # - 持仓信息
    # - 当前时间
    # - 回测环境状态

    g.security = "000001.XSHE"
    # `g` 是聚宽里常见的全局变量容器
    #
    # 你可以把它理解成：
    # "给整个策略临时存放全局变量的小盒子"
    #
    # 这里把要交易的股票保存到：
    # g.security
    #
    # `"000001.XSHE"` 是聚宽股票代码写法之一
    # 这里：
    # - `000001` 是证券代码
    # - `XSHE` 表示深交所
    #
    # 这不是普通 Python 固定格式，
    # 而是平台约定的证券标识方式

    run_daily(market_open, time="every_bar")
    # `run_daily(...)` 是聚宽平台提供的调度函数
    #
    # 它的作用是：
    # 告诉平台，"请你以后按设定时机去执行某个函数"
    #
    # 这里传进去的是：
    # `market_open`
    #
    # 也就是说：
    # 后面平台会按这个规则去调用 `market_open(context)`
    #
    # `time="every_bar"`
    # 表示按平台定义的每个 bar 时点执行
    #
    # 这是明显的平台写法，
    # 不是普通本地 Python 会自动认识的函数


def market_open(context):
    # 这是你真正写策略逻辑的主要函数
    #
    # 平台会按前面 `run_daily(...)` 注册的规则，
    # 反复调用这个函数
    #
    # 所以你可以把它理解成：
    # "每次平台让策略看一眼市场时，这里做什么"

    security = g.security
    # 从全局变量容器 `g` 里取出股票代码
    #
    # 这样写的好处是：
    # 前面已经把股票写进 `g.security`
    # 这里就不需要每次重新手动写一次股票代码

    close_data = attribute_history(security, 5, "1d", ["close"])
    # `attribute_history(...)` 是聚宽平台提供的历史数据接口
    #
    # 它的作用是：
    # 按你给的条件，去平台数据源取历史数据
    #
    # 这里几个参数的意思：
    #
    # `security`
    # 表示要取哪只股票的数据
    #
    # `5`
    # 表示最近 5 个周期
    #
    # `"1d"`
    # 表示周期单位是日线
    # 也就是说：最近 5 天
    #
    # `["close"]`
    # 表示只取收盘价这一列
    #
    # 所以这一整句的意思就是：
    # "去取这只股票最近 5 个交易日的收盘价"

    MA5 = close_data["close"].mean()
    # 这一行是在计算 5 日均线
    #
    # `close_data["close"]`
    # 取出收盘价这一列
    #
    # `.mean()`
    # 求平均值
    #
    # 因为这里刚好拿了最近 5 天数据，
    # 所以它就是 MA5

    current_price = close_data["close"][-1]
    # 这一行是在取"当前价格"
    #
    # 从策略意图上理解，这里是想拿最近这组收盘价里的最后一个值，
    # 也就是当前最新价格
    #
    # 你要特别记住这个学习点：
    #
    # 在聚宽平台里，这样写通常可以工作：
    # `close_data["close"][-1]`
    #
    # 但在普通本地 pandas 环境里，
    # `[-1]` 不一定天然就等于"最后一个元素"
    # 有时会被理解成"按标签取索引 -1"
    #
    # 所以这就是典型的：
    # "平台代码看起来像普通 Python，
    # 但底层环境行为不一定完全一样"

    cash = context.portfolio.available_cash
    # `context.portfolio.available_cash`
    # 表示当前账户可用现金
    #
    # 这是平台维护好的账户对象里的属性
    # 不是你自己手动算出来的
    #
    # 这就是平台环境和普通本地脚本很不一样的地方：
    # 平台已经帮你准备好了"账户状态"

    if current_price > 1.01 * MA5:
        # 这是买入条件
        #
        # 条件意思是：
        # 如果当前价格 > 1.01 * MA5
        #
        # 也就是：
        # 当前价格比 5 日均线高出 1%
        #
        # 你可以把它理解成：
        # "价格明显强于 5 日均线时，认为可以考虑买入"
        #
        # 注意：
        # 这里的 1.01 是一个可修改参数
        # 如果改成 1.02，表示要高出 2% 才买
        # 如果改成 1.00，表示只要高于均线就买

        order_value(security, cash)
        # `order_value(...)` 是聚宽平台提供的下单函数
        #
        # 它的意思是：
        # 按金额下单
        #
        # 这里传的是：
        # - 股票代码
        # - 当前全部可用现金
        #
        # 所以这句策略意图上相当于：
        # "如果满足条件，就把当前现金尽量买进去"
        #
        # 这是一种非常简单直接的入门写法
        # 但也说明：
        # 当前策略没有做更细的仓位管理

        log.info("买入 %s" % (security))
        # `log.info(...)` 是聚宽平台日志函数
        #
        # 这里的作用是：
        # 在日志里记录一条"买入"的提示信息
        #
        # `%s` 是字符串格式化占位符
        # 会把 security 的值填进去

    elif current_price < MA5 and context.portfolio.positions[security].closeable_amount > 0:
        # 这是卖出条件
        #
        # 条件分成两部分：
        #
        # 第一部分：
        # `current_price < MA5`
        # 表示当前价格跌回 5 日均线下方
        #
        # 第二部分：
        # `context.portfolio.positions[security].closeable_amount > 0`
        # 表示当前这只股票有可卖出的持仓数量
        #
        # 为什么第二部分很重要：
        # 因为如果你根本没持仓，
        # 就没必要去执行"卖出"

        order_target(security, 0)
        # `order_target(...)` 也是聚宽平台提供的下单函数
        #
        # 它的意思是：
        # 把目标持仓调整到某个数量
        #
        # 这里写成：
        # `order_target(security, 0)`
        #
        # 意思就是：
        # "把这只股票的目标持仓调成 0"
        #
        # 也就是：清仓

        log.info("卖出 %s" % (security))
        # 在日志里记录一条"卖出"的提示信息

    record(stock_price=current_price)
    # `record(...)` 是聚宽平台提供的记录函数
    #
    # 它通常用于：
    # 把你想观察的变量记下来
    # 这样回测时更容易画图或查看
    #
    # 这里记录的是：
    # `stock_price=current_price`
    #
    # 意思就是：
    # 把当前价格记录下来，方便后续观察


